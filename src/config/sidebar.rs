const DEFAULT_MACHINE_FEEDER_INTERVAL_SECS: u64 = 15;
const MIN_MACHINE_FEEDER_INTERVAL_SECS: u64 = 2;

fn deserialize_feeder_interval<'de, D>(deserializer: D) -> Result<u64, D::Error>
where
    D: serde::Deserializer<'de>,
{
    let secs = u64::deserialize(deserializer)?;
    if secs < MIN_MACHINE_FEEDER_INTERVAL_SECS {
        return Err(serde::de::Error::custom(format!(
            "machine feeder_interval_secs must be at least {MIN_MACHINE_FEEDER_INTERVAL_SECS}"
        )));
    }
    Ok(secs)
}

/// Machine header rows in the multi-machine sidebar.
///
/// The collapse marker and the connection badge stay fixed on the first line;
/// `rows` lays out everything between them. Values for `$name` tokens and the
/// `services` dots come from `feeder`, an argv command the client runs every
/// `feeder_interval_secs` that prints one JSON document on stdout.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(default)]
pub struct MachinesSidebarConfig {
    #[serde(deserialize_with = "deserialize_sidebar_rows")]
    pub rows: MachineSidebarRows,
    pub row_gap: u16,
    pub feeder: Vec<String>,
    #[serde(deserialize_with = "deserialize_feeder_interval")]
    pub feeder_interval_secs: u64,
    /// Show only a machine's first row while it has nothing to report: no
    /// blocked agents, no feeder value marked with `!`, no service down, and
    /// a live connection.
    pub fold_healthy: bool,
    /// Size the machines and agents sections to their content until the
    /// divider is dragged by hand.
    pub auto_split: bool,
}

impl Default for MachinesSidebarConfig {
    fn default() -> Self {
        Self {
            rows: vec![vec![MachineSidebarToken::Label]],
            row_gap: DEFAULT_SIDEBAR_ROW_GAP,
            feeder: Vec::new(),
            feeder_interval_secs: DEFAULT_MACHINE_FEEDER_INTERVAL_SECS,
            fold_healthy: false,
            auto_split: false,
        }
    }
}

