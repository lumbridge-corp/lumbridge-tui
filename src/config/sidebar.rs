        assert_eq!(machines.feeder, vec!["/usr/local/bin/fleet", "--json"]);
        assert_eq!(machines.feeder_interval_secs, 30);
        let round_trip: SidebarConfig = toml::from_str(
            &toml::to_string(&SidebarConfig {
                machines,
                ..Default::default()
            })
            .unwrap(),
        )
        .unwrap();
